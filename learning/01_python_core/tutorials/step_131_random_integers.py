"""
Микро-шаг 131: Случайные целые числа (random.randint).
Использование модуля random из стандартной библиотеки Python.
В ML генерация случайных чисел нужна для разбиения данных на train/test,
инициализации весов нейросети и сэмплирования (выборки подмножества данных).
"""

# Импорт стандартного модуля random
import random

print("Генерация случайных целых чисел:")

# Генерация одного случайного числа в диапазоне [1, 6]
dice_roll: int = random.randint(1, 6)
print(f"  Бросок кубика: {dice_roll}")

# Генерация нескольких случайных чисел
print("\nСерия из 5 случайных чисел от 1 до 100:")
for i in range(1, 6):
    random_number: int = random.randint(1, 100)
    print(f"  Число {i}: {random_number}")

# Практический пример из ML: выбор случайного индекса из датасета
print("\nСлучайный индекс из датасета (размер 1000):")
dataset_size: int = 1000
random_index: int = random.randint(0, dataset_size - 1)
print(f"  Выбран индекс: {random_index}")

# Выбор случайного элемента из диапазона с шагом
# Например, случайный ID эксперимента из 100 возможных
print("\nСлучайный ID эксперимента (от 1 до 100):")
experiment_id: int = random.randint(1, 100)
print(f"  Experiment ID: {experiment_id}")