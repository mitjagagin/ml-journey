"""
Микро-шаг 135: Чтение всего файла (Reading the Entire File).
Открытие текстового файла и чтение его содержимого целиком.
В ML это используется для загрузки конфигов (файлов с настройками)
или чтения сырых текстовых датасетов (наборов данных).
"""

# Путь к файлу (так как файл лежит в той же папке, достаточно только имени)
filename: str = "pi_digits.txt"

# Открываем файл. Конструкция with гарантирует, что файл закроется
# автоматически, как только мы выйдем из этого блока с отступом.
with open(filename) as file_object:
    # Считываем всё содержимое файла в одну большую строку
    contents: str = file_object.read()

print("Содержимое файла:")
print(contents)