"""
Микро-шаг 97: Значения по умолчанию (Default Values).
Параметры функции со значениями по умолчанию, которые можно переопределить.
В ML это используется для гиперпараметров (настроек модели): задаём
разумный дефолт и меняем только то, что нужно в конкретном эксперименте.
"""

# Определяем функцию с параметром по умолчанию
# epochs: int = 10 означает: если при вызове не передали epochs, используй 10
def describe_experiment(model_name: str, dataset_name: str, epochs: int = 10) -> None:
    print(f"Модель: {model_name}")
    print(f"Датасет: {dataset_name}")
    print(f"Эпохи: {epochs}")

# Вызов БЕЗ указания epochs — используется значение по умолчанию (10)
print("Эксперимент с дефолтными эпохами:")
describe_experiment("LogisticRegression", "Wine")

# Вызов С переопределением epochs через именованный аргумент
print("\nЭксперимент с переопределёнными эпохами:")
describe_experiment("RandomForest", "Titanic", epochs=50)