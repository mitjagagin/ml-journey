"""
Микро-шаг 28: Цикл for для перебора списка.
Цикл for выполняет блок кода с отступом для каждого элемента коллекции.
"""

# Список моделей для оценки
models_to_evaluate: list[str] = ["Logistic Regression", "Random Forest", "XGBoost"]

# Цикл for: переменная 'model' по очереди принимает каждое значение из списка
for model in models_to_evaluate:
    # Этот код С ОТСТУПОМ выполняется для КАЖДОЙ модели
    print(f"Начинаю оценку модели: {model}")
    print(f"-> Модель {model} успешно обучена.\n")

# Этот код БЕЗ отступа выполняется только ОДИН раз после завершения цикла
print("Все модели из списка успешно оценены!")