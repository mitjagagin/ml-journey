"""
Микро-шаг 83: Числовой ввод с int() (Using int() to Accept Numerical Input).
Функция input() всегда возвращает строку, даже если пользователь
ввёл цифры. Чтобы использовать ввод как число, его нужно
преобразовать с помощью функции int().
В ML это нужно для получения числовых параметров от пользователя,
например, количества эпох (полных прогонов модели по данным).
"""

# Сохраняем текст подсказки в переменную
age_prompt: str = "Сколько эпох обучения модели вы хотите задать? "

# Функция input() возвращает СТРОКУ, даже если ввели цифры
epochs_str: str = input(age_prompt)

# Преобразуем строку в целое число
epochs: int = int(epochs_str)

# Выводим результат
print(f"\nВы задали {epochs} эпох обучения.")

# Проверяем, достаточно ли эпох для обучения
if epochs < 10:
    print("Предупреждение: модель может не успеть обучиться.")
elif epochs >= 10:
    print("Хорошо! Модель получит достаточно данных для обучения.")