"""
Микро-шаг 99: Избежание ошибок аргументов (Avoiding Argument Errors).
Демонстрация ошибок при передаче неверного количества аргументов.
В ML при сборке пайплайнов (последовательности шагов) ошибки TypeError —
самые частые. Умение читать текст ошибки помогает быстро найти пропущенный параметр.
"""

# Функция ожидает ровно 2 аргумента
def describe_pet(animal_type: str, pet_name: str) -> None:
    print(f"\nУ меня есть {animal_type}.")
    print(f"Моего {animal_type} зовут {pet_name}.")

# Правильный вызов (2 аргумента для 2 параметров)
describe_pet("хомяк", "Харри")

