"""
Микро-шаг 39: Простая статистика со списками чисел (min, max, sum).
Встроенные функции для поиска минимума, максимума и суммы элементов списка.
В ML это аналогично анализу метрик: поиску минимальной ошибки (loss),
максимальной точности (accuracy) или суммированию значений в батче.
"""

# Список значений метрики (например, accuracy в процентах за 5 эпох обучения)
accuracies: list[int] = [85, 92, 88, 95, 90]

# Вычисление статистики с помощью встроенных функций Python
min_accuracy: int = min(accuracies)
max_accuracy: int = max(accuracies)
total_accuracy: int = sum(accuracies)

# Вывод результатов
print(f"Минимальная точность: {min_accuracy}%")
print(f"Максимальная точность: {max_accuracy}%")
print(f"Сумма точностей: {total_accuracy}%")

# Вычисление среднего значения (бонус: используем len() для получения длины списка)
# len() возвращает количество элементов в списке (в данном случае 5)
average_accuracy: float = total_accuracy / len(accuracies)
print(f"\nСредняя точность: {average_accuracy}%")