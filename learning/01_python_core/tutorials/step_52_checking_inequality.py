"""
Микро-шаг 52: Проверка неравенства (Checking for Inequality).
Оператор != возвращает True, если значения не равны, и False, если равны.
В ML это используется для валидации входящих данных:
например, отклонения файлов неверного формата до попадания в пайплайн.
"""

# Ожидаемый формат данных в пайплайне
expected_format: str = "csv"

# Формат, который фактически пришёл из источника
actual_format: str = "json"

# Проверка: отличается ли фактический формат от ожидаемого
print("Проверка неравенства (пришёл неверный формат):")
if actual_format != expected_format:
    print(f"  Формат неверный: пришёл '{actual_format}', ожидался '{expected_format}'")
else:
    print("  Формат корректен")

# Теперь источник прислал верный формат
actual_format = "csv"

print("\nПроверка неравенства (пришёл верный формат):")
if actual_format != expected_format:
    print(f"  Формат неверный: пришёл '{actual_format}', ожидался '{expected_format}'")
else:
    print("  Формат корректен")