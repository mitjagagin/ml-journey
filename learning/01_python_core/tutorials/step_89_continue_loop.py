"""
Микро-шаг 89: Пропуск итерации с continue (Using continue in a Loop).
Оператор continue пропускает оставшуюся часть текущей итерации
цикла и переходит к следующей, не прерывая цикл полностью.
В ML это используется для фильтрации невалидных данных:
например, пропускать примеры с ошибками в пайплайне (последовательности
шагов обработки данных) или невалидные метрики (числовые оценки качества).
"""

# Список метрик (числовых оценок качества модели)
# Некоторые значения невалидные: accuracy не может быть < 0 или > 1
metrics: list[float] = [0.85, -0.1, 0.92, 0.78, 1.5, 0.88]

# Счетчик валидных метрик
valid_count: int = 0

# Проходим по всем метрикам
for metric in metrics:
    # Проверяем на невалидные значения
    if metric < 0 or metric > 1:
        print(f"Пропускаем невалидную метрику: {metric}")
        continue

    # Этот код выполнится только для валидных метрик
    print(f"Обрабатываем метрику: {metric}")
    valid_count += 1

print(f"\nВсего обработано валидных метрик: {valid_count}")