"""
Микро-шаг 51: Игнорирование регистра при проверке (Ignoring Case).
Приведение строк к нижнему регистру перед сравнением.
В ML это критически важно при очистке текстовых данных (NLP)
и обработке конфигураций, чтобы избежать ошибок из-за разного написания.
"""

# Название фреймворка, полученное из внешнего источника (например, из конфига)
framework: str = "PyTorch"

# Обычное сравнение: не сработает из-за регистра
print("Обычное сравнение (чувствительно к регистру):")
if framework == "pytorch":
    print("  Фреймворк совпадает!")
else:
    print("  Фреймворк не совпадает.")

# Сравнение с игнорированием регистра
print("\nСравнение с игнорированием регистра:")
if framework.lower() == "pytorch":
    print("  Фреймворк совпадает!")
else:
    print("  Фреймворк не совпадает.")

# Проверка: изменилась ли исходная переменная?
print("\nИсходная переменная не изменилась:")
print(f"  framework: {framework}")