"""
Микро-шаг 141: Добавление текста в конец файла (Appending to a File).
Режим 'a' позволяет добавить новые строки без удаления старых данных.
В ML так можно дописывать логи (журналы событий) или метрики
(числовые оценки качества модели), не удаляя историю.
"""

# Имя файла, в который будем добавлять текст
filename: str = "programming.txt"

# Открываем файл в режиме 'a' (append - добавление).
# Если файл уже есть, новые данные будут записаны в конец файла.
# Если файла нет, он будет создан.
with open(filename, "a") as file_object:
    # Добавляем новую строку в конец файла
    file_object.write("I love building ML pipelines.\n")

# Проверяем результат: читаем файл и печатаем содержимое
with open(filename) as file_object:
    contents: str = file_object.read()

print("Содержимое файла после добавления строки:")
# rstrip() убирает лишний перенос строки в конце вывода
print(contents.rstrip())