"""
Микро-шаг 64: Проверка особых элементов в цикле (Checking for Special Items).
Комбинация цикла for и условий для проверки каждого элемента списка.
В ML это используется для поэлементной валидации датасета, фильтрации
выбросов и обработки особых случаев в пайплайне.
"""

# Датасет: значения признака "возраст" с потенциальными аномалиями
ages: list[int] = [25, 34, -5, 42, 150, 28, 0, 31]

# Валидация каждого элемента в цикле
print("Валидация значений возраста:")
for age in ages:
    if age < 0:
        print(f"  {age} — отрицательное значение, ошибка данных")
    elif age > 120:
        print(f"  {age} — превышает максимальный возраст, выброс")
    else:
        print(f"  {age} — корректное значение")

# Статусы моделей в системе
model_statuses: list[str] = ["ready", "training", "failed", "ready", "deprecated"]

# Обработка каждого статуса по отдельности
print("\nОбработка статусов моделей:")
for status in model_statuses:
    if status == "ready":
        print(f"  '{status}' — модель доступна для инференса")
    elif status == "deprecated":
        print(f"  '{status}' — модель устарела, пропуск")
    else:
        print(f"  '{status}' — модель в работе")