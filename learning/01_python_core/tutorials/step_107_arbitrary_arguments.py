"""
Микро-шаг 107: Передача произвольного количества аргументов (Arbitrary Arguments).
Использование звёздочки (*) для приёма любого количества позиционных аргументов.
В ML это нужно, когда функция должна принимать переменное число признаков
(колонок данных) или моделей для ансамбля (группы моделей).
"""

# Звёздочка перед именем параметра говорит Python:
# "Собери все переданные позиционные аргументы в кортеж features"
def print_model_features(*features: str) -> None:
    print("Признаки для обучения модели:")
    for feature in features:
        print(f"  - {feature}")

# Передаём 2 признака
print("\nЭксперимент 1 (базовые признаки):")
print_model_features("возраст", "доход")

# Передаём 4 признака — функция работает без изменений!
print("\nЭксперимент 2 (расширенные признаки):")
print_model_features("возраст", "доход", "город", "кредитный_рейтинг")

# Передаём 1 признак
print("\nЭксперимент 3 (один признак):")
print_model_features("только_доход")