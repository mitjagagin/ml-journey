"""
Микро-шаг 94: Определение функции (Defining a Function).
Создание и вызов простейшей функции с помощью ключевого слова def.
В ML функции используются для разделения пайплайна (последовательности шагов)
на логические блоки, например, загрузка данных или обучение модели.
"""

# Определяем функцию, которая выводит статус обучения
def print_training_status() -> None:
    print("Статус: Обучение модели начато.")
    print("Эпоха (один полный прогон по данным): 1 из 10")

# Вызываем функцию
print("Запуск пайплайна:")
print_training_status()

# Вызываем функцию еще раз, чтобы показать переиспользование кода
print("\nПерезапуск пайплайна:")
print_training_status()