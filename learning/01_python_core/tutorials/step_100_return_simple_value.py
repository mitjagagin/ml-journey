"""
Микро-шаг 100: Возврат простого значения (Returning a Simple Value).
Функция возвращает результат вычисления с помощью оператора return.
В ML функции возвращают метрики (числовые оценки качества модели),
чтобы использовать их дальше в пайплайне обучения.
"""

# Функция ВОЗВРАЩАЕТ результат, а не печатает его
def calculate_accuracy(correct: int, total: int) -> float:
    result: float = correct / total
    return result

# Сохраняем возвращённое значение в переменную
accuracy: float = calculate_accuracy(85, 100)

print("Точность модели:")
print(f"  Правильных: 85 из 100")
print(f"  Точность: {accuracy}")

# Используем возвращённое значение в условии
if accuracy > 0.8:
    print("\nМодель готова к оценке на тестовых данных.")
else:
    print("\nМодель требует дополнительного обучения.")