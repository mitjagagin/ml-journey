# ── Реляционная модель (Relational Model) ──
# Данные хранятся в таблицах с фиксированной схемой
# Связи между таблицами через ключи (ID)

print("Реляционная модель (таблицы):")

# Таблица users
users_table: list[dict[str, str]] = [
    {"user_id": "1", "name": "Alice", "city_id": "10"},
    {"user_id": "2", "name": "Bob", "city_id": "20"},
]

# Таблица cities (связь через city_id)
cities_table: list[dict[str, str]] = [
    {"city_id": "10", "city_name": "Moscow"},
    {"city_id": "20", "city_name": "Berlin"},
]

print("  Таблица users:")
for row in users_table:
    print(f"    {row}")

print("  Таблица cities:")
for row in cities_table:
    print(f"    {row}")

print("  Связь: users.city_id -> cities.city_id")

# ── Документная модель (Document Model) ──
# Данные хранятся как гибкие вложенные документы
# Нет фиксированной схемы, связи встроены

print("\nДокументная модель (документы):")

user_documents: list[dict[str, str | dict[str, str] | list[str]]] = [
    {
        "name": "Alice",
        "city": {"name": "Moscow", "country": "Russia"},
        "hobbies": ["reading", "hiking"],
    },
    {
        "name": "Bob",
        "city": {"name": "Berlin", "country": "Germany"},
        "hobbies": ["cycling"],
    },
]

for doc in user_documents:
    print(f"  Документ:")
    print(f"    имя:    {doc['name']}")
    print(f"    город:  {doc['city']['name']} ({doc['city']['country']})")
    print(f"    хобби:  {doc['hobbies']}")

# ── Сравнение моделей данных ──
print("\nСравнение моделей данных:")

models: list[dict[str, str]] = [
    {
        "модель": "Реляционная (SQL)",
        "пример": "PostgreSQL, MySQL",
        "структура": "таблицы, фиксированная схема",
        "связи": "через ключи (JOIN)",
        "плюс": "целостность данных, сложные запросы",
        "минус": "жёсткая схема, сложно менять",
    },
    {
        "модель": "Документная (NoSQL)",
        "пример": "MongoDB, Firebase",
        "структура": "гибкие документы (JSON)",
        "связи": "встроенные в документ",
        "плюс": "гибкость, быстрая разработка",
        "минус": "нет стандартных JOIN",
    },
    {
        "модель": "Key-Value (NoSQL)",
        "пример": "Redis, DynamoDB",
        "структура": "ключ -> значение",
        "связи": "нет явных связей",
        "плюс": "очень быстрый доступ по ключу",
        "минус": "нет сложных запросов",
    },
    {
        "модель": "Графовая (NoSQL)",
        "пример": "Neo4j",
        "структура": "узлы и рёбра",
        "связи": "явные рёбра между узлами",
        "плюс": "идеально для сетей и связей",
        "минус": "узкая специализация",
    },
]

for model in models:
    print(f"\n  {model['модель']}:")
    print(f"    пример:     {model['пример']}")
    print(f"    структура:  {model['структура']}")
    print(f"    связи:      {model['связи']}")
    print(f"    плюс:       {model['плюс']}")
    print(f"    минус:      {model['минус']}")

