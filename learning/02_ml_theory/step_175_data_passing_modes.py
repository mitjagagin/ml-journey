"""
Микро-шаг 175: Способы передачи данных (Modes of Dataflow).
Демонстрация трех основных способов передачи данных между процессами в ML-системах.
В ML это определяет архитектуру пайплайна: насколько он сложен, надежен и быстр.
"""


# 1. Передача через базы данных (Data Passing Through Databases)
# Процесс А записывает данные в БД, Процесс Б читает их оттуда позже.
# Плюсы: надежность, простота. Минусы: задержка из-за записи/чтения на диск.
def database_mode(data: list[str]) -> None:
    """Имитирует передачу данных через базу данных."""
    print("  [Database] Процесс А: Запись данных в хранилище...")
    print("  [Database] Процесс Б: Чтение данных из хранилища...")
    print(f"  [Database] Обработано: {data}\n")


# 2. Передача через сервисы (Data Passing Through Services)
# Процесс А отправляет синхронный запрос (например, REST API) Процессу Б.
# Плюсы: прямой контроль. Минусы: жесткая связь (coupling), Процесс Б должен быть онлайн.
def service_mode(data: str) -> None:
    """Имитирует синхронную передачу данных через REST API."""
    print(f"  [Service] Процесс А: Отправка REST-запроса с данными '{data}'...")
    print(f"  [Service] Процесс Б: Мгновенный ответ и обработка '{data}'...\n")


# 3. Передача через потоковые транспорты (Real-Time Transport / Message Brokers)
# Процесс А публикует событие в брокер (Kafka), Процесс Б подписывается на него.
# Плюсы: слабая связь (decoupling), высокая скорость. Минусы: сложность инфраструктуры.
def realtime_transport_mode(event: str) -> None:
    """Имитирует асинхронную передачу через брокер сообщений."""
    print(f"  [Real-time] Процесс А: Публикация события '{event}' в брокер сообщений...")
    print(f"  [Real-time] Процесс Б: Асинхронное получение и обработка '{event}'...\n")


if __name__ == "__main__":
    print("Архитектурные сценарии передачи данных в ML-системах\n")

    print("1. Режим: Через базу данных (Batch ETL)")
    database_mode(["user_1_click", "user_2_click"])

    print("2. Режим: Через сервисы (Sync API)")
    service_mode("predict_fraud_score_for_transaction_123")

    print("3. Режим: Через потоковый транспорт (Async Message Broker)")
    realtime_transport_mode("new_user_signup_event")