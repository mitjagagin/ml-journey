"""
Микро-шаг 161: Типичные сценарии использования ML (Common ML Use Cases).
Маппинг бизнес-задач на стандартные типы ML-задач (классификация, регрессия, ранжирование).
В ML это критически важный этап фрейминга (framing): перевод бизнес-потребности
на язык математики и алгоритмов перед началом разработки.
"""

# Вложенный словарь: бизнес-задача -> её характеристики в ML
business_problems: dict[str, dict[str, str]] = {
    "Предсказать стоимость квартиры": {
        "ml_task": "Регрессия (Regression)",
        "example": "Модель выдает непрерывное число (например, 150000.50).",
    },
    "Определить, является ли транзакция мошеннической": {
        "ml_task": "Классификация (Classification)",
        "example": "Модель выдает дискретную категорию (0 = нормальная, 1 = фрод).",
    },
    "Показать пользователю наиболее релевантные товары": {
        "ml_task": "Ранжирование (Ranking)",
        "example": "Модель сортирует список товаров от наиболее подходящих к наименее.",
    },
}


def frame_ml_problem(problem_description: str) -> None:
    """Анализирует бизнес-задачу и предлагает тип ML-модели."""
    print(f"Бизнес-задача: {problem_description}")

    # Проверяем, есть ли задача в нашем словаре
    if problem_description in business_problems:
        # Извлекаем вложенный словарь с характеристиками
        task_info: dict[str, str] = business_problems[problem_description]
        print(f"  Тип ML-задачи: {task_info['ml_task']}")
        print(f"  Как это работает: {task_info['example']}\n")
    else:
        print("  Ошибка: Неизвестная бизнес-задача. Возможно, это не задача для ML.\n")


print("Фрейминг бизнес-задач в ML-термины:")
print("")

# 1. Задача на регрессию (непрерывное значение)
frame_ml_problem("Предсказать стоимость квартиры")

# 2. Задача на классификацию (бинарный выбор)
frame_ml_problem("Определить, является ли транзакция мошеннической")

# 3. Задача на ранжирование (сортировка)
frame_ml_problem("Показать пользователю наиболее релевантные товары")

# 4. Задача, которая не подходит под стандартный ML (генерация креатива без данных)
frame_ml_problem("Придумать абсолютно новый слоган для бренда")