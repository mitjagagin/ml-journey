"""
Микро-шаг 159: Традиционное ПО против Машинного обучения (Traditional vs ML Software).
Сравнение двух подходов к решению задач: жесткие правила против поиска закономерностей в данных.
В ML это фундамент: понимание разницы помогает правильно собирать данные
и настраивать процесс обучения вместо того, чтобы писать правила вручную.
"""

# --- ПОДХОД 1: Традиционное программное обеспечение ---
# Инженер сам придумывает и прописывает правила (if/else) для обработки данных.
# Формула: Данные + Правила (код) = Ответы

def classify_temperature_traditional(temperature: float) -> str:
    """Классифицирует температуру по жестко заданным правилам."""
    if temperature < 0:
        return "Холодно"
    elif 0 <= temperature <= 25:
        return "Комфортно"
    else:
        return "Жарко"

# Признак (feature) — это входная характеристика объекта, которую мы подаем на вход.
# Здесь наш признак — это число 15.0.
current_feature: float = 15.0
traditional_result: str = classify_temperature_traditional(current_feature)

print("Традиционное ПО (Данные + Правила = Ответы):")
print(f"  Входной признак: {current_feature}")
print(f"  Вердикт программы: {traditional_result}")


# --- ПОДХОД 2: Машинное обучение ---
# Инженер не пишет правила. Он собирает исторические данные и правильные ответы.
# Алгоритм сам находит закономерности и создает модель.
# Формула: Данные + Ответы = Модель (Правила)

# 1. Собираем исторические данные.
# historical_features — список признаков (температур в прошлом).
historical_features: list[float] = [-5.0, 10.0, 20.0, 30.0]

# historical_labels — список меток (правильных ответов для этих температур).
# Метка (label) — это правильный ответ, который мы хотим, чтобы модель научилась предсказывать.
historical_labels: list[str] = ["Холодно", "Комфортно", "Комфортно", "Жарко"]

# 2. Симулируем Обучение (training).
# Обучение (training) — это процесс, в ходе которого алгоритм анализирует
# исторические данные и настраивает свои внутренние параметры.
# В реальности алгоритм создает сложную математическую функцию.
# Мы симулируем результат обучения в виде простого словаря.
# Этот словарь и есть наша Модель (model).
# Модель (model) — это результат обучения, функция, которая принимает новые признаки и выдает предсказания.
learned_model: dict[str, str] = {
    "low_temp": "Холодно",
    "medium_temp": "Комфортно",
    "high_temp": "Жарко"
}

# 3. Используем модель для предсказания на новом признаке.
new_feature: float = 15.0

# Простая логика подготовки данных для нашей симулированной модели
if new_feature < 0:
    model_input: str = "low_temp"
elif 0 <= new_feature <= 25:
    model_input = "medium_temp"
else:
    model_input = "high_temp"

# Модель выдает предсказание
ml_prediction: str = learned_model[model_input]

print("\nМашинное обучение (Данные + Ответы = Модель):")
print(f"  Исторические данные: {len(historical_features)} примеров")
print(f"  Новый признак: {new_feature}")
print(f"  Предсказание модели: {ml_prediction}")