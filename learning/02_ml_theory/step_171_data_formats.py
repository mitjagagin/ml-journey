"""
Микро-шаг 171: Форматы данных (Data Formats).
Демонстрирует разницу между строковым (row-major) и колонковым (column-major)
хранением, а также между текстовыми и бинарными форматами.
В ML это используется для выбора оптимального формата хранения датасета:
скорость чтения и объём памяти напрямую влияют на процесс обучения модели.
"""

# Исходные данные: 3 записи о пользователях
users: list[dict[str, str]] = [
    {"name": "Alice", "age": "30", "city": "Moscow"},
    {"name": "Bob", "age": "25", "city": "Berlin"},
    {"name": "Carol", "age": "35", "city": "Tokyo"},
]

# ── Строковое хранение (Row-Major) ──
# Данные лежат по строкам: каждая запись целиком
print("Строковое хранение (Row-Major):")
print("  Каждая запись хранится целиком, одна за другой.")
for record in users:
    print(f"  {record}")

# ── Колонковое хранение (Column-Major) ──
# Данные лежат по колонкам: все значения одного поля вместе
print("\nКолонковое хранение (Column-Major):")
print("  Все значения одной колонки хранятся вместе.")

columns: dict[str, list[str]] = {
    "name": ["Alice", "Bob", "Carol"],
    "age": ["30", "25", "35"],
    "city": ["Moscow", "Berlin", "Tokyo"],
}

for column_name, values in columns.items():
    print(f"  {column_name}: {values}")

# ── Сравнение текстовых и бинарных форматов ──
print("\nСравнение форматов хранения:")

formats: list[dict[str, str]] = [
    {
        "формат": "CSV (текстовый)",
        "пример": "name,age,city\\nAlice,30,Moscow",
        "плюс": "читается человеком, простой",
        "минус": "большой объём, медленное чтение",
    },
    {
        "формат": "JSON (текстовый)",
        "пример": '{"name": "Alice", "age": 30}',
        "плюс": "гибкая структура, совместим с API",
        "минус": "избыточность (ключи повторяются)",
    },
    {
        "формат": "Parquet (бинарный)",
        "пример": "бинарные колонки со сжатием",
        "плюс": "компактный, быстрое чтение колонок",
        "минус": "не читается без специальных инструментов",
    },
    {
        "формат": "Avro (бинарный)",
        "пример": "бинарные строки со схемой",
        "плюс": "компактный, поддержка эволюции схемы",
        "минус": "не читается без специальных инструментов",
    },
]

for fmt in formats:
    print(f"\n  {fmt['формат']}:")
    print(f"    пример: {fmt['пример']}")
    print(f"    плюс:   {fmt['плюс']}")
    print(f"    минус:  {fmt['минус']}")

# ── Когда что использовать ──
print("\nКогда что использовать (по Huyen):")
print("  Текстовые (CSV, JSON):")
print("    - малые датасеты, прототипирование")
print("    - обмен данными через API")
print("  Бинарные (Parquet, Avro):")
print("    - большие датасеты в production")
print("    - когда важна скорость чтения и объём")
print("  Row-major:")
print("    - когда нужно читать записи целиком")
print("    - запись новых данных по одной")
print("  Column-major:")
print("    - аналитические запросы по отдельным полям")
print("    - ML: читаем признаки (колонки) для обучения")