"""
Микро-шаг 163: Бизнес- и ML-цели (Business and ML Objectives).
Демонстрация сопоставления бизнес-целей с конкретными ML-целями и метриками.
В ML это критически важно: оптимизация не той метрики может привести
к росту вычислительных затрат без реального улучшения бизнес-показателей.
"""

# Словарь для хранения примеров целей.
# Ключ: бизнес-цель (str).
# Значение: вложенный словарь с ml_целью и метрикой (dict[str, str]).
goal_mapping: dict[str, dict[str, str]] = {
    "Увеличить удержание пользователей": {
        "ml_objective": "Предсказать вероятность оттока пользователя в течение 30 дней",
        "metric": "ROC-AUC (площадь под ROC-кривой)"
    },
    "Снизить затраты на логистику": {
        "ml_objective": "Спрогнозировать точное время доставки заказа",
        "metric": "MAE (Средняя абсолютная ошибка)"
    },
    "Повысить конверсию в покупку": {
        "ml_objective": "Ранжировать товары по вероятности клика пользователя",
        "metric": "NDCG (Normalized Discounted Cumulative Gain)"
    }
}

print("Сопоставление бизнес-целей и ML-целей:")
for business_goal, ml_details in goal_mapping.items():
    print(f"Бизнес-цель: {business_goal}")
    print(f"  ML-цель: {ml_details['ml_objective']}")
    print(f"  Метрика: {ml_details['metric']}\n")