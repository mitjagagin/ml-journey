# Категория 1: Пользовательские данные (User-Generated Data)
# Данные, которые создаются действиями пользователей
user_data_sources: dict[str, str] = {
    "клики и просмотры": "сайт, мобильное приложение",
    "поисковые запросы": "внутренний поиск, Google",
    "отзывы и оценки": "карточки товаров, приложения",
    "загруженные файлы": "фото, документы, аудио",
}

print("Пользовательские данные (User-Generated Data):")
for source, origin in user_data_sources.items():
    print(f"  {source} -> {origin}")

# Категория 2: Системные данные (System-Generated Data)
# Данные, которые система собирает автоматически
system_data_sources: dict[str, str] = {
    "логи сервера": "автоматически при каждом запросе",
    "метрики производительности": "CPU, память, latency",
    "транзакции базы данных": "каждая покупка, платёж",
    "сенсоры устройств": "GPS, акселерометр, температура",
}

print("\nСистемные данные (System-Generated Data):")
for source, origin in system_data_sources.items():
    print(f"  {source} -> {origin}")

# Категория 3: Внешние данные (Third-Party / Public Data)
# Данные, которые приходят извне
external_data_sources: dict[str, str] = {
    "открытые датасеты": "Kaggle, UCI, государственные порталы",
    "API сторонних сервисов": "погода, курсы валют, карты",
    "веб-скрапинг": "публичные сайты (с учётом законодательства)",
    "купленные данные": "данные брокеров, партнёров",
}

print("\nВнешние данные (Third-Party / Public Data):")
for source, origin in external_data_sources.items():
    print(f"  {source} -> {origin}")

# Сравнение характеристик источников
print("\nСравнение характеристик источников:")

sources_comparison: list[dict[str, str]] = [
    {
        "источник": "клики пользователя",
        "формат": "JSON-события",
        "частота": "реальное время",
        "качество": "среднее (шум, боты)",
    },
    {
        "источник": "транзакции БД",
        "формат": "таблицы (SQL)",
        "частота": "реальное время",
        "качество": "высокое (валидация)",
    },
    {
        "источник": "открытый датасет",
        "формат": "CSV / Parquet",
        "частота": "однократно / редко",
        "качество": "зависит от автора",
    },
]

for source in sources_comparison:
    print(f"  {source['источник']}:")
    print(f"    формат:   {source['формат']}")
    print(f"    частота:  {source['частота']}")
    print(f"    качество: {source['качество']}")

