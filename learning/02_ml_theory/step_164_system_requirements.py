"""
Микро-шаг 164: Требования к ML-системам (System Requirements).
Четыре ключевых свойства production-ready ML-систем:
reliability, scalability, maintainability, adaptability.
В ML-инженерии эти требования критичны: модель, не отвечающая им,
быстро деградирует в продакшене и требует дорогостоящего переобучения.
"""

# Словарь с четырьмя требованиями к ML-системам.
# Ключ: название требования (str).
# Значение: вложенный словарь с описанием и примером (dict[str, str]).
requirements: dict[str, dict[str, str]] = {
    "Reliability": {
        "description": "Система работает корректно на ожидаемых и неожиданных входных данных",
        "example": "Модель предсказания оттока возвращает валидный ответ даже при пропусках в данных клиента"
    },
    "Scalability": {
        "description": "Система сохраняет качество работы при росте нагрузки или объёма данных",
        "example": "Сервис рекомендаций обрабатывает 10 000 запросов в секунду без деградации latency"
    },
    "Maintainability": {
        "description": "Систему легко обновлять, мониторить и передавать между командами",
        "example": "ML-пайплайн покрыт тестами, имеет версию модели и документацию в репозитории"
    },
    "Adaptability": {
        "description": "Система быстро адаптируется к изменениям в данных и бизнес-среде",
        "example": "Модель переобучается на свежих данных при обнаружении drift (дрейфа данных)"
    }
}

print("Требования к production-ready ML-системам:")
for name, details in requirements.items():
    print(f"{name}:")
    print(f"  Описание: {details['description']}")
    print(f"  Пример:   {details['example']}\n")