"""
Микро-шаг 167: Framing ML Problems + Types of ML Tasks.
Демонстрация сопоставления бизнес-проблем с типами задач машинного обучения.
В ML это используется для корректного выбора подхода (например, классификации или регрессии)
на этапе проектирования системы, что напрямую влияет на сбор данных и выбор метрик.
"""

# Словарь для хранения примеров формулировок задач
ml_task_examples: dict[str, list[str]] = {
    "Supervised Learning (Обучение с учителем)": [
        "Бизнес-цель: Предсказать, отменит ли клиент подписку (Churn prediction). -> ML-задача: Бинарная классификация.",
        "Бизнес-цель: Оценить стоимость дома на основе его характеристик. -> ML-задача: Регрессия."
    ],
    "Unsupervised Learning (Обучение без учителя)": [
        "Бизнес-цель: Сегментировать клиентов для таргетированного маркетинга. -> ML-задача: Кластеризация.",
        "Бизнес-цель: Найти аномальные транзакции в логах. -> ML-задача: Обнаружение аномалий (Anomaly detection)."
    ],
    "Reinforcement Learning (Обучение с подкреплением)": [
        "Бизнес-цель: Оптимизировать маршрут доставки дрона в реальном времени. -> ML-задача: Управление (Control) / RL."
    ]
}


def print_framing_examples() -> None:
    """Выводит примеры формулировки ML-задач с форматированием."""
    print("Примеры формулировки задач машинного обучения (Framing):\n")

    for task_type, examples in ml_task_examples.items():
        print(f"🔹 {task_type}:")
        for example in examples:
            print(f"  - {example}")
        print()  # Пустая строка для разделения блоков


if __name__ == "__main__":
    print_framing_examples()