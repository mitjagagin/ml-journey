"""
Микро-шаг 160: Когда использовать ML (When to Use ML).
Применение чек-листа для оценки целесообразности использования машинного обучения.
В ML это критически важный навык: умение отказаться от сложной ML-модели
в пользу простых правил (if/else) или SQL, если задача не требует ML.
"""


def evaluate_task(task_name: str, is_complex_pattern: bool, has_data: bool, is_error_tolerant: bool) -> None:
    """Оценивает задачу и рекомендует, нужен ли здесь ML."""
    print(f"Задача: {task_name}")

    # 1. Если задачу можно решить простыми правилами, ML не нужен
    if not is_complex_pattern:
        print("  Решение: Используйте обычные правила (if/else) или SQL.")
        print("  Причина: Паттерн слишком прост, ML здесь избыточен.\n")
        return

    # 2. Если нет данных, ML обучать не на чем
    if not has_data:
        print("  Решение: ML пока неприменим.")
        print("  Причина: Нет данных для обучения модели.\n")
        return

    # 3. Если цена ошибки слишком высока (нет толерантности), ML опасен
    if not is_error_tolerant:
        print("  Решение: Используйте детерминированный алгоритм или не используйте автоматизацию.")
        print("  Причина: ML вероятностен и может ошибаться, что недопустимо.\n")
        return

    # 4. Если все условия пройдены, задача подходит для ML
    print("  Решение: Отличный кандидат для ML!")
    print("  Причина: Сложный паттерн, есть данные, а ошибки допустимы.\n")


print("Оценка задач на целесообразность применения ML:")
print("")

# 1. Расчет налога (простые правила, нет толерантности к ошибкам)
evaluate_task(
    task_name="Расчет подоходного налога",
    is_complex_pattern=False,
    has_data=True,
    is_error_tolerant=False
)

# 2. Фильтрация четных чисел (простые правила)
evaluate_task(
    task_name="Отфильтровать только четные числа в списке",
    is_complex_pattern=False,
    has_data=True,
    is_error_tolerant=True
)

# 3. Распознавание рукописных цифр (сложный паттерн, есть данные, ошибки терпимы)
evaluate_task(
    task_name="Распознавание рукописных цифр на почте",
    is_complex_pattern=True,
    has_data=True,
    is_error_tolerant=True
)

# 4. Предсказание редкой болезни без исторических данных (нет данных)
evaluate_task(
    task_name="Диагностика новой редкой болезни по симптомам",
    is_complex_pattern=True,
    has_data=False,
    is_error_tolerant=False
)