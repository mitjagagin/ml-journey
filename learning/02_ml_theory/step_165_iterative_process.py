"""
Микро-шаг 165: Итеративный процесс (Iterative Process).
Демонстрация 8 этапов разработки ML-системы как циклического процесса.
В ML-инженерии этот цикл повторяется многократно: после деплоя модель
возвращается к сбору данных или фреймингу из-за изменения данных и целей.
"""

# Словарь этапов итеративного процесса разработки ML-системы.
# Ключ: номер этапа (str).
# Значение: вложенный словарь с названием, описанием и результатом этапа.
iterative_process: dict[str, dict[str, str]] = {
    "1": {
        "stage": "Framing the problem",
        "description": "Определение бизнес-цели, ML-цели и метрик успеха",
        "output": "Документ с требованиями и критериями успеха"
    },
    "2": {
        "stage": "Data collection and labeling",
        "description": "Сбор сырых данных и создание размеченного датасета",
        "output": "Готовый датасет train/val/test"
    },
    "3": {
        "stage": "Feature engineering",
        "description": "Создание и отбор признаков (features) для модели",
        "output": "Набор признаков, улучшающих качество модели"
    },
    "4": {
        "stage": "Model selection and training",
        "description": "Выбор архитектуры модели и её обучение на данных",
        "output": "Обученная модель с весами"
    },
    "5": {
        "stage": "Evaluation",
        "description": "Оценка модели на валидационных и тестовых данных",
        "output": "Значения метрик (accuracy, F1, MAE и др.)"
    },
    "6": {
        "stage": "Deployment",
        "description": "Развёртывание модели в продакшен-среде",
        "output": "Работающий ML-сервис, доступный пользователям"
    },
    "7": {
        "stage": "Monitoring and maintenance",
        "description": "Отслеживание качества модели и обнаружение drift",
        "output": "Алерты о деградации модели или дрейфе данных"
    },
    "8": {
        "stage": "Iteration",
        "description": "Возврат к любому предыдущему этапу на основе мониторинга",
        "output": "Новая гипотеза → новый цикл разработки"
    }
}

print("Итеративный процесс разработки ML-системы:")
for number, details in iterative_process.items():
    print(f"Этап {number}: {details['stage']}")
    print(f"  Описание: {details['description']}")
    print(f"  Результат: {details['output']}\n")