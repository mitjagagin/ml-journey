"""
Микро-шаг 174: Режимы потока данных (Modes of Dataflow).
Демонстрация концептуальной разницы между пакетной (batch) и потоковой (stream) обработкой.
В ML это определяет, как часто модель получает новые данные для предсказаний или переобучения.
"""

import time


# --- Пакетная обработка (Batch Processing) ---
def process_batch(data_batch: list[str]) -> None:
    """Обрабатывает список данных целиком за один раз."""
    print(f"  [Batch] Получен пакет из {len(data_batch)} записей.")
    print(f"  [Batch] Обрабатываем все записи сразу...")
    for item in data_batch:
        print(f"    - Обработано: {item}")
    print("  [Batch] Пакетная обработка завершена.\n")


# --- Потоковая обработка (Streaming Processing) ---
def process_stream(event: str) -> None:
    """Обрабатывает одно событие сразу при его поступлении."""
    print(f"  [Stream] Получено новое событие: '{event}'")
    print(f"  [Stream] Мгновенная обработка события...\n")


if __name__ == "__main__":
    print("Бизнес-сценарий: Анализ кликов пользователей на сайте\n")

    # Сценарий 1: Пакетная обработка (например, раз в сутки для аналитики)
    print("1. Пакетный режим (Batch):")
    daily_clicks = ["клик_1", "клик_2", "клик_3"]
    process_batch(daily_clicks)

    # Сценарий 2: Потоковая обработка (например, для мгновенного обнаружения фрода)
    print("2. Потоковый режим (Stream):")
    live_events = ["покупка_товара_A", "попытка_оплаты_картой_X", "вход_в_аккаунт"]

    for event in live_events:
        process_stream(event)
        # Имитация задержки между реальными событиями в потоке
        time.sleep(0.5)