"""
Микро-шаг 136: Пути к файлам (File Paths).
Чтение файлов из подпапок с использованием относительных путей.
В ML датасеты (наборы данных) и конфиги (настройки) хранятся в отдельных папках,
а не в папке с кодом.
"""
from pathlib import Path

# Относительный путь: мы говорим Python искать папку 'data'
# внутри той папки, где лежит этот скрипт.
# Path автоматически подставит правильные слеши для твоей ОС (Windows или Mac/Linux).
file_path: Path = Path("data/model_config.txt")

# Метод read_text() сам открывает файл, читает его целиком и сразу закрывает.
# Это современная и безопасная замена конструкции with open(...).
contents: str = file_path.read_text()

print("Конфигурация модели:")
print(contents)