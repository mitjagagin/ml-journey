"""
Микро-шаг 137: Создание списка строк из файла (Making a List of Lines from a File).
Метод readlines() читает файл и возвращает список строк.
В ML так можно читать датасет (набор данных) или лог (журнал событий),
если каждая строка файла является отдельной записью.
"""

# Имя файла с числом pi (файл лежит рядом со скриптом)
filename: str = "pi_digits.txt"

# Открываем файл и читаем его построчно
with open(filename) as file_object:
    # readlines() возвращает список, где каждый элемент - одна строка из файла
    lines: list[str] = file_object.readlines()

print("Содержимое файла построчно:")
for line in lines:
    # Убираем скрытый символ переноса строки в конце каждой строки
    print(line.rstrip())