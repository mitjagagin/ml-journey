"""
Микро-шаг 87: Использование флага (Using a Flag).
Флаг — это булева переменная (True/False), которая управляет
работой цикла. Вместо проверки введенного значения в условии while,
мы проверяем ввод внутри цикла и меняем флаг при команде выхода.
В ML флаги управляют пайплайнами (последовательностями шагов):
например, флаг is_training определяет режим работы модели —
обучение или инференс (применение модели к новым данным).
"""

# Многострочная подсказка для пользователя
prompt: str = "\nВведите промпт (запрос) для языковой модели:"
prompt += "\n(Введите 'quit', чтобы завершить сбор): "

# Флаг: активен ли сбор промптов. Начинаем с True — сбор идет
active: bool = True

# Цикл работает, пока флаг active равен True
while active:
    message: str = input(prompt)

    # Если пользователь ввел 'quit', меняем флаг на False
    if message == "quit":
        active = False
    else:
        # Выводим только реальные промпты, не команду выхода
        print(f"Получен промпт: {message}")

print("\nСбор промптов завершен!")