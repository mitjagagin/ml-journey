"""
Микро-шаг 85: Цикл while в действии (The while Loop in Action).
Цикл while выполняет блок кода, пока условие истинно (True).
В отличие от for, который работает фиксированное количество раз,
while работает до тех пор, пока условие не станет ложным (False).
В ML это используется для итеративных процессов: например, обучение
модели продолжается, пока не будет достигнуто нужное количество эпох
(полных прогонов модели по данным).
"""

# Модель должна обучиться 5 эпох (полных прогонов по данным)
max_epochs: int = 5

# Текущая эпоха начинается с 1
current_epoch: int = 1

# Цикл while выполняется, пока current_epoch не превысит max_epochs
while current_epoch <= max_epochs:
    print(f"Идёт эпоха {current_epoch} из {max_epochs}")
    # Увеличиваем текущую эпоху на 1.
    # Без этой строки условие никогда не станет False и цикл будет бесконечным!
    current_epoch += 1

print("\nОбучение модели завершено!")