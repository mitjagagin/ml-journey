"""
Микро-шаг 86: Пользователь выбирает момент выхода (Letting the User Choose When to Quit).
Цикл while работает, пока пользователь не введет специальное
значение 'quit' (выйти). Это базовый паттерн интерактивного ввода.
В ML так работают интерактивные скрипты: сбор промптов (запросов)
для языковой модели продолжается, пока пользователь не решит закончить.
"""

# Многострочная подсказка для пользователя
prompt: str = "\nВведите промпт (запрос) для языковой модели:"
prompt += "\n(Введите 'quit', чтобы завершить сбор): "

# Начальное значение — пустая строка, чтобы первый цикл запустился
message: str = ""

# Цикл работает, пока пользователь не введет 'quit'
while message != "quit":
    message = input(prompt)
    print(f"Получен промпт: {message}")