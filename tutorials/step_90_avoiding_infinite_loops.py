"""
Микро-шаг 90: Избегание бесконечных циклов (Avoiding Infinite Loops).
Бесконечный цикл — это цикл, который никогда не завершается,
потому что условие всегда остается истинным (True).
В ML бесконечные циклы в продакшен-пайплайнах (последовательностях
шагов обработки данных) могут привести к зависанию системы или
бесконечному обучению модели без остановки.
"""

# НЕПРАВИЛЬНЫЙ КОД (бесконечный цикл) — закомментирован, чтобы не запускать
# current_epoch: int = 1
# max_epochs: int = 5
#
# while current_epoch <= max_epochs:
#     print(f"Эпоха {current_epoch}")
#     # ОШИБКА: забыли увеличить current_epoch!
#     # Условие всегда будет True: 1 <= 5, 1 <= 5, 1 <= 5...
#     # Цикл никогда не остановится
#
# Если вы случайно запустили бесконечный цикл, нажмите Ctrl+C,
# чтобы принудительно остановить программу

# ПРАВИЛЬНЫЙ КОД — с инкрементом
current_epoch: int = 1
max_epochs: int = 5

print("Начинаем обучение модели:")
while current_epoch <= max_epochs:
    print(f"  Эпоха {current_epoch} из {max_epochs}")
    # ВАЖНО: увеличиваем счетчик на каждой итерации
    current_epoch += 1

print("Обучение завершено!")

# Еще один пример: проверка условия перед циклом
# Иногда цикл не должен запускаться вообще
target_accuracy: float = 0.95
current_accuracy: float = 0.97

print(f"\nЦелевая точность: {target_accuracy}")
print(f"Текущая точность: {current_accuracy}")

# Цикл не запустится, потому что условие сразу False
while current_accuracy < target_accuracy:
    print("Этот текст не выведется")
    current_accuracy += 0.01

print("Модель уже достигла нужного качества, обучение не требуется")