"""
Микро-шаг 49: Простой пример условной инструкции (A Simple Example).
Цикл for с проверкой if внутри: элементы обрабатываются по-разному
в зависимости от условия. Это основа ветвления логики в коде.
В ML это используется для выделения важного элемента из списка:
например, лучшая модель в отчёте или этап пайплайна, требующий внимания.
"""

# Список моделей-кандидатов в проекте
models: list[str] = ["linear", "forest", "boosting", "neural"]

# Лучшая модель по результатам оценки
best_model: str = "boosting"

# Вывод отчёта: лучшая модель выделяется заглавными буквами
print("Отчёт по моделям-кандидатам:")
for model in models:
    if model == best_model:
        print(f"BEST MODEL: {model.upper()}")
    else:
        print(f" Candidate: {model.title()}")