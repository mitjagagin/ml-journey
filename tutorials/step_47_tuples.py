'''
Микро-шаг 47: Кортежи (Tuples).
Кортежи — это неизменяемые списки. Используются для данных,
которые не должны меняться: размеры изображений, координаты,
гиперпараметры модели.
В ML кортежи защищают критические настройки от случайного изменения.
'''

# Размеры изображения (ширина, высота) — не должны меняться
dimensions: tuple[int, int] = (200, 50)

print("Размеры изображения:")
print(f"  Ширина: {dimensions[0]}")
print(f"  Высота: {dimensions[1]}")

# Итерация по кортежу работает так же, как по списку
print("\nВсе размеры:")
for dimension in dimensions:
    print(f"  {dimension}")

# Попытка изменить элемент кортежа вызовет ошибку TypeError.
# Раскомментируй строку ниже, чтобы увидеть ошибку:
# dimensions[0] = 250

# Но можно переопределить переменную целиком
dimensions = (400, 100)

print("\nНовые размеры после переопределения:")
print(f"  Ширина: {dimensions[0]}")
print(f"  Высота: {dimensions[1]}")