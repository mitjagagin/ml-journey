"""
Микро-шаг 84: Оператор остатка от деления (The Modulo Operator %).
Оператор % возвращает остаток от деления одного числа на другое,
а не сам результат деления.
В ML это используется для работы с батчами (пакетами данных):
например, чтобы определить, сколько данных останется после формирования
полных батчей для обучения модели.
"""

# Пример 1: Проверка четности номера эпохи (полного прогона модели)
# Если остаток от деления на 2 равен 0 — число четное
epoch: int = 10
remainder: int = epoch % 2

print(f"Эпоха {epoch}:")
if remainder == 0:
    print("  Номер эпохи четный")
else:
    print("  Номер эпохи нечетный")

# Пример 2: Разделение датасета (набора данных) на батчи
# Допустим, у нас 100 примеров в датасете, а размер батча 32
dataset_size: int = 100
batch_size: int = 32

# Вычисляем остаток данных, который не поместится в полный батч
leftover_data: int = dataset_size % batch_size

print(f"\nРазмер датасета: {dataset_size} примеров")
print(f"Размер батча: {batch_size}")
print(f"Остаток данных (неполный батч): {leftover_data} примеров")

# Пример 3: Логирование метрик (числовых оценок качества)
# Выводим статус только на каждой 5-й эпохе
current_epoch: int = 15
log_interval: int = 5

if current_epoch % log_interval == 0:
    print(f"\nЭпоха {current_epoch}: время сохранить метрики модели!")