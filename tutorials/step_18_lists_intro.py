"""
Микро-шаг 18: Введение в списки (Lists).
Списки — это упорядоченные коллекции элементов, которые можно изменять.
В ML они часто используются для хранения названий признаков (features),
меток классов или конфигураций пайплайна.
"""

# Создаем список названий алгоритмов машинного обучения.
# Указываем type hint list[str], чтобы показать, что список содержит строки.
ml_algorithms: list[str] = ["Linear Regression", "Random Forest", "XGBoost", "Neural Network"]

# Выводим весь список целиком
print(f"Доступные алгоритмы: {ml_algorithms}")

# Выводим первый элемент.
# ВАЖНО: Индексация в Python начинается с 0, а не с 1!
first_algorithm: str = ml_algorithms[0]
print(f"Первый алгоритм в списке (индекс 0): {first_algorithm}")

# Выводим последний элемент, используя отрицательную индексацию.
# Индекс -1 всегда обращается к последнему элементу списка, что очень удобно.
last_algorithm: str = ml_algorithms[-1]
print(f"Последний алгоритм в списке (индекс -1): {last_algorithm}")