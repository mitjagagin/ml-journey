"""
Микро-шаг 88: Выход из цикла с break (Using break to Exit a Loop).
Оператор break немедленно завершает цикл, не проверяя условие снова.
Это альтернатива флагу: вместо установки переменной мы сразу выходим.
В ML break полезен, когда нужно прервать процесс при достижении условия:
например, остановить перебор датасетов (наборов данных), когда
пользователь решил прекратить работу.
"""

# Многострочная подсказка для пользователя
prompt: str = "\nВведите название датасета (набора данных), который хотите загрузить:"
prompt += "\n(Введите 'quit', чтобы завершить): "

# while True — бесконечный цикл, выходим только через break
while True:
    dataset: str = input(prompt)

    # Если пользователь ввел 'quit', немедленно выходим из цикла
    if dataset == "quit":
        break
    else:
        print(f"Загружаем датасет: {dataset}")

print("\nРабота с датасетами завершена!")