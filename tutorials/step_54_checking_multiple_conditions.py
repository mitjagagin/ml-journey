"""
Микро-шаг 54: Проверка нескольких условий (Checking Multiple Conditions).
Операторы and и or объединяют несколько проверок в одно условие.
В ML это используется при контроле качества моделей: деплой разрешён,
только если точность И скорость в норме, а переобучение стартует,
если упала точность ИЛИ выросла задержка.
"""

# Требования к модели для выхода в продакшен
min_accuracy: int = 90
max_latency: int = 100  # миллисекунды на ответ

# Фактические показатели модели
model_accuracy: int = 93
model_latency: int = 80

# Проверка через and: оба условия должны быть выполнены
print("Проверка готовности через AND (оба условия):")
if model_accuracy >= min_accuracy and model_latency <= max_latency:
    print("  Модель готова к деплою")
else:
    print("  Модель не готова к деплою")

# Сценарий: точность в норме, но задержка выросла
new_accuracy: int = 92
new_latency: int = 120

# Проверка через or: достаточно хотя бы одного условия
print("\nПроверка переобучения через OR (хотя бы одно условие):")
if new_accuracy < min_accuracy or new_latency > max_latency:
    print("  Запускаем переобучение модели")
else:
    print("  Модель работает стабильно")