"""
Микро-шаг 82: Функция input() (How the input() Function Works).
Функция input() приостанавливает выполнение программы и ждет,
пока пользователь введет текст и нажмет Enter. Введенные данные
сохраняются в переменную как строка (string).
В ML это используется для получения текстового промпта (запроса)
от пользователя для нейросети или запроса пути к датасету (набору данных).
"""

# Запрашиваем у пользователя имя
# Функция input() выводит подсказку и ждет ввода
name: str = input("Введите ваше имя: ")

# Запрашиваем любимую задачу машинного обучения
# Многострочная подсказка для ясности (концепция из 7.1.1)
prompt: str = "\nКакая ваша любимая задача ML?"
prompt += "\n(Например: классификация, генерация текста, прогнозирование): "
favorite_task: str = input(prompt)

# Выводим результат, используя f-strings (пройдено в Главе 2)
print(f"\nПривет, {name}!")
print(f"Отличный выбор! Направление '{favorite_task}' очень востребовано.")

# Проверяем ввод с помощью if (пройдено в Главе 5)
# Используем .lower() (пройдено в Главе 2), чтобы сравнение не зависело от регистра
if favorite_task.lower() == "генерация текста":
    print("Генерация текста — это основа современных LLM (больших языковых моделей)!")