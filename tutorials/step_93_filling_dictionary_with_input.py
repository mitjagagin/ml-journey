"""
Микро-шаг 93: Заполнение словаря пользовательским вводом (Filling a Dictionary with User Input).
Цикл while с input() позволяет собирать данные от пользователя
и сохранять их как пары ключ-значение в словаре.
В ML это используется для сбора конфигурации модели: пользователь
задает гиперпараметры (настройки модели, которые задаёт человек
до обучения), и они сохраняются в словарь для дальнейшего использования.
"""

# Словарь для хранения гиперпараметров (настроек модели)
hyperparameters: dict[str, str] = {}

print("Сбор гиперпараметров (настроек) для модели машинного обучения.")
print("Введите 'quit' в поле 'Имя параметра', чтобы завершить сбор.\n")

# Цикл работает, пока пользователь не введет 'quit'
while True:
    # Запрашиваем имя параметра
    param_name: str = input("Имя параметра (например: epochs, learning_rate): ")

    # Проверяем команду выхода
    if param_name == "quit":
        break

    # Запрашиваем значение параметра
    param_value: str = input(f"Значение для {param_name}: ")

    # Добавляем пару ключ-значение в словарь
    hyperparameters[param_name] = param_value
    print(f"  Добавлено: {param_name} = {param_value}\n")

# Выводим все собранные гиперпараметры
print("\nСобранные гиперпараметры модели:")
for param, value in hyperparameters.items():
    print(f"  {param}: {value}")