"""
Микро-шаг 30: Избегание ошибок отступов.
Демонстрация правильных отступов в циклах.
"""

# Список моделей для оценки
models_to_evaluate: list[str] = ["Logistic Regression", "Random Forest", "XGBoost"]

print("=== Начало оценки моделей ===\n")

# Правильный отступ: код внутри цикла (4 пробела)
for model in models_to_evaluate:
    print(f"Оцениваю модель: {model}")
    print(f"-> Модель {model} успешно обучена.")
    print(f"-> Метрики сохранены в лог.\n")

# Правильно: БЕЗ отступа — выполняется один раз ПОСЛЕ цикла
