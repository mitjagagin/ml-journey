# tutorials/step_08_whitespace.py
"""Демонстрация служебных символов: табуляция и перенос строки."""

# \t — добавляет табуляцию (отступ, как клавиша Tab)
print("Languages:\tPython\tC++\tJava")

# \n — добавляет перенос строки (как клавиша Enter)
print("Steps to deploy a model:\n1. Train\n2. Save\n3. Dockerize\n4. Deploy")

# Комбинация \n\t — перенос строки + табуляция (красивое форматирование списка)
print("Model metrics:\n\t- Accuracy: 0.95\n\t- F1-score: 0.92")