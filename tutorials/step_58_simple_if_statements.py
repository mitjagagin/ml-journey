"""
Микро-шаг 58: Простые условные инструкции (Simple if Statements).
Конструкция if без else выполняет код только при истинном условии.
В ML это используется для side-effects: сохранение чекпоинтов, отправка
алертов, логирование событий — действий, которые нужны только при
определённых условиях, без альтернативного поведения.
"""

# Статус валидации модели
is_validated: bool = True

# Простая проверка: сохраняем чекпоинт только если модель прошла валидацию
print("Проверка валидации модели:")
if is_validated:
    print("  Сохраняем чекпоинт модели в реестр")
# Если is_validated == False, ничего не происходит

# Проверка дрейфа данных
drift_detected: bool = False

print("\nПроверка дрейфа данных:")
if drift_detected:
    print("  Обнаружен дрейф, отправляем алерт в Slack")
# Если дрейфа нет, алерт не отправляется

# Уверенность предсказания
confidence: float = 0.92
threshold: float = 0.8

print("\nПроверка уверенности предсказания:")
if confidence >= threshold:
    print(f"  Предсказание принимается (уверенность {confidence})")
# Если уверенность ниже порога, предсказание отклоняется (без явного else)

# Логируем только важные события
log_level: str = "info"

print("\nУсловное логирование:")
if log_level == "error":
    print("  ОШИБКА: записываем в error.log")
if log_level == "warning":
    print("  ПРЕДУПРЕЖДЕНИЕ: записываем в warning.log")
if log_level == "info":
    print("  ИНФО: записываем в info.log")
# Только одно из условий сработает